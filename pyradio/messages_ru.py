''' Russian translations of the in-program help texts

    The help windows are defined in messages_system.py; this module only
    overrides them when the user interface language is Russian.

    Rules used in this file:
      - all {key} placeholders are kept as is; they are replaced with the
        actual shortcut in use (kb2str), so that the help always matches
        the configured shortcuts;
      - the "<*>" separator marks the two columns of a help line; the
        left part holds the keys (up to 21 characters), the right part is
        printed starting at column 22;
      - "!" starts a section header, "%" a full width separator;
      - leading "__" are printed as spaces;
      - "|" toggles the highlight color; it is used for keys and headings
        only, because the English text uses it to highlight the letter
        that triggers an action, which makes little sense in Russian.
'''
from os import environ

from .keyboard import kb2str
from .tts import Priority


def get_ui_language():
    ''' Return the language code of the user interface

        The language is taken from the standard locale variables; only
        languages we have translations for are reported, everything else
        falls back to English.
    '''
    for a_var in ('LC_ALL', 'LC_MESSAGES', 'LANGUAGE', 'LANG'):
        lang = environ.get(a_var, '')
        if lang:
            lang = lang.split(':')[0].split('.')[0].split('_')[0].lower()
            if lang in ('ru', ):
                return lang
    return 'english'


